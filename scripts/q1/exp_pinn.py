"""Experiment G (+C3): is the PINN parameter inconsistency an optimisation problem or a
property of the soft-constrained formulation?

All runs use the 1D slab model of the comparison (training mixes of the hold-out split,
seed 0, paper settings unless stated):
    fixed_classical  parameter head pre-trained on the classical slab parameters and frozen;
                     only the field network is trained (is the classical solution a good
                     point of the PINN loss?)
    warm_start       head pre-trained on the classical parameters, then everything trained
    lambda_100       PDE weight 100 instead of 10
    synthetic        SYNTHETIC training curves generated by the slab FD solver from the
                     classical slab parameters (known truth, no model error, no noise)
For every run: final loss terms, training RMSE, parameters vs classical slab fits, and the
solver check (FD solver run with the PINN parameters vs PINN output and vs data).
Output: results/q1/pinn/{runs.csv, theta.csv}
"""
from __future__ import annotations

import argparse
import json
import time
from multiprocessing import Pool

import numpy as np
import pandas as pd
import torch

from common import ROOT, TEST_MIXES, load_data, metrics, out_dir
from pinn_moisture.fd_solver import FDSolver
from pinn_moisture.physics import config_for
from pinn_moisture.pinn import DTYPE, Trainer, TrainConfig

RUNS = {"fixed_classical": dict(pre=True, freeze=True), "warm_start": dict(pre=True),
        "lambda_100": dict(tcfg={"lambda_pde": 100.0}), "synthetic": dict(synthetic=True),
        "reference": dict()}


def run(name):
    torch.set_num_threads(1)
    spec = RUNS[name]
    cfg = config_for("slab")
    d = load_data()
    train = d[~d.Mix.isin(TEST_MIXES)].copy()
    cl = pd.read_csv(ROOT / "results/slab/classical_fits.csv").set_index("Mix")
    fd = FDSolver(cfg, n_cells=160)
    if spec.get("synthetic"):
        for m, idx in train.groupby("Mix").groups.items():
            th = {k: float(cl.loc[m, k]) for k in cfg.identified}
            train.loc[idx, "S_frac"] = fd.solve(th, train.loc[idx, "Time_d"].to_numpy(), rtol=1e-8, atol=1e-10)[0]
    tcfg = TrainConfig(seed=0, **spec.get("tcfg", {}))
    tr = Trainer(train, cfg, tcfg)
    mixes = train.drop_duplicates("Mix").Mix.tolist()
    pre_err = None
    if spec.get("pre"):
        head = tr.model.head
        target = torch.tensor(cl.loc[mixes, list(cfg.identified)].to_numpy(), dtype=DTYPE)
        scale = head.hi - head.lo
        opt = torch.optim.Adam(head.parameters(), lr=1e-2)
        for _ in range(4000):
            opt.zero_grad()
            loss = torch.mean(((head(tr.c_mix) - target) / scale) ** 2)
            loss.backward()
            opt.step()
        pre_err = float((head(tr.c_mix) - target).abs().max())
        if spec.get("freeze"):
            for p in head.parameters():
                p.requires_grad_(False)
    t0 = time.time()
    tr.fit(verbose=False)
    th = tr.predict_theta(train)
    last = tr.history[-1]
    # solver check on the training mixes
    fwd, mod = [], []
    for m, g in train.groupby("Mix"):
        t = g.Time_d.to_numpy()
        row = th[th.Mix == m].iloc[0]
        fwd.append(fd.solve({k: float(row[k]) for k in cfg.identified}, t)[0])
        mod.append(tr.predict_avg(g))
    fwd, mod = np.concatenate(fwd), np.concatenate(mod)
    obs = np.concatenate([g.S_frac.to_numpy() for _, g in train.groupby("Mix")])
    th = th.set_index("Mix")
    res = {"run": name, "time_s": time.time() - t0, "pre_head_maxerr": pre_err,
           "loss_total": last["total"], "loss_data": last["data"], "loss_pde": last["pde"], "loss_neu": last["neu"],
           "train_rmse": last["rmse"], "pde_rms": tr.pde_residual_stats(),
           "fwd_vs_model_r2": metrics(mod, fwd)["r2"], "fwd_vs_model_rmse": metrics(mod, fwd)["rmse"],
           "fwd_vs_data_r2": metrics(obs, fwd)["r2"], "fwd_vs_data_rmse": metrics(obs, fwd)["rmse"],
           "mae_Dv_vs_classical": float((th.log10_Dv - cl.loc[th.index, "log10_Dv"]).abs().mean()),
           "bias_K_vs_classical": float((th.log10_K - cl.loc[th.index, "log10_K"]).mean()),
           "mae_K_vs_classical": float((th.log10_K - cl.loc[th.index, "log10_K"]).abs().mean())}
    thr = th.reset_index().assign(run=name)
    return res, thr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", default=["fixed_classical", "warm_start", "synthetic", "lambda_100"])
    ap.add_argument("--workers", type=int, default=2)
    a = ap.parse_args()
    out = out_dir("pinn")
    old = pd.read_csv(out / "runs.csv").to_dict("records") if (out / "runs.csv").exists() else []
    oldt = [pd.read_csv(out / "theta.csv")] if (out / "theta.csv").exists() else []
    with Pool(a.workers) as pool:
        for res, thr in pool.imap_unordered(run, a.runs):
            old = [r for r in old if r["run"] != res["run"]] + [res]
            oldt = [t[t.run != res["run"]] for t in oldt] + [thr]
            pd.DataFrame(old).to_csv(out / "runs.csv", index=False)
            pd.concat(oldt).to_csv(out / "theta.csv", index=False)
            print(json.dumps(res, default=float), flush=True)


if __name__ == "__main__":
    main()
